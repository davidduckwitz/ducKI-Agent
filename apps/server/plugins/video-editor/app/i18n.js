(function () {
  var STORAGE_KEY = "video-editor-lang";
  function detectLang() {
    try {
      var stored = window.localStorage.getItem(STORAGE_KEY);
      if (stored === "de" || stored === "en") return stored;
    } catch (e) { /* ignore */ }
    var nav = (navigator.language || "de").toLowerCase();
    return nav.indexOf("de") === 0 ? "de" : "en";
  }

  window.currentLang = detectLang();

  window.t = function t(key, vars) {
    var dict = window.I18N[window.currentLang] || window.I18N.de;
    var str = dict[key] != null ? dict[key] : (window.I18N.de[key] != null ? window.I18N.de[key] : key);
    if (vars) {
      Object.keys(vars).forEach(function (k) {
        str = str.replace(new RegExp("\\{" + k + "\\}", "g"), vars[k]);
      });
    }
    return str;
  };

  window.setLang = function setLang(lang) {
    window.currentLang = lang === "en" ? "en" : "de";
    try { window.localStorage.setItem(STORAGE_KEY, window.currentLang); } catch (e) { /* ignore */ }
  };

  /** Applies data-i18n / data-i18n-placeholder / data-i18n-title on the current DOM. */
  window.applyI18n = function applyI18n(root) {
    var scope = root || document;
    scope.querySelectorAll("[data-i18n]").forEach(function (el) {
      el.innerHTML = window.t(el.getAttribute("data-i18n"));
    });
    scope.querySelectorAll("[data-i18n-placeholder]").forEach(function (el) {
      el.setAttribute("placeholder", window.t(el.getAttribute("data-i18n-placeholder")));
    });
    scope.querySelectorAll("[data-i18n-title]").forEach(function (el) {
      el.setAttribute("title", window.t(el.getAttribute("data-i18n-title")));
    });
  };
})();
